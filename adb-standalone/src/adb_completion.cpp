std::string Join(const std::vector<std::string>& v, const char* sep = " ") {
    std::string out;
    for (size_t i = 0; i < v.size(); i++) {
        if (i) out += sep;
        out += v[i];
    }
    return out;
}

std::vector<std::string> CommandList() {
    std::vector<std::string> out;
    for (const auto& c : adbhelp::Commands()) {
        if (std::find(out.begin(), out.end(), c.name) == out.end()) out.push_back(c.name);
    }
    // wait-for[-TRANSPORT]-STATE... is a pattern, not a literal; list the states
    // the way upstream's own completion does.
    static const char* kWaitStates[] = {"device", "recovery", "rescue", "sideload",
                                        "bootloader", "disconnect"};
    for (const char* st : kWaitStates) {
        out.push_back(std::string("wait-for-") + st);
        out.push_back(std::string("wait-for-usb-") + st);
        out.push_back(std::string("wait-for-local-") + st);
        out.push_back(std::string("wait-for-any-") + st);
    }
    return out;
}

std::string OptionList() { return Join(adbhelp::Options()); }

std::string LangList() {
    size_t n = 0;
    const adbi18n::LangInfo* langs = adbi18n::LangTable(&n);
    std::string out;
    for (size_t i = 0; i < n; i++) {
        if (i) out += " ";
        out += langs[i].code;
    }
    return out;
}

// Options that consume the next argv token; the command scanner skips them and
// their value so `adb -s SERIAL pu<TAB>` still completes `push`.
const char* kValueOpts = "-s -t -H -P -L -z -e";

const char* kRebootTargets = "bootloader recovery sideload fastboot";
const char* kSyncTargets = "all data system vendor product system_ext odm oem";
const char* kMdnsSubs = "check services resolve";
const char* kForwardSubs = "list remove remove-all";
const char* kWaitStates = "device recovery rescue sideload bootloader disconnect";
const char* kCompression = "none any fast best lz4 zstd brotli";
// `adb shell` subcommands worth completing specially; anything else falls back
// to the device's own executable list.
const char* kShellSubs = "dumpsys am pm ls cat settings getprop svc wm input cmd";

// ===========================================================================
// bash
// ===========================================================================
std::string BashScript() {
    std::ostringstream o;
    o << R"B(# bash completion for adb-m / adb-meowarch.
# GENERATED by `adb-m --shell-completion=bash` — do not edit by hand; regenerate
# so the vocabulary always matches the binary.
# Install as /usr/share/bash-completion/completions/adb-m (and the same content
# as .../adb-meowarch: bash-completion only autoloads the file named after the
# command being completed).
#
# Uses ${COMP_WORDS[0]} as the binary, so one script serves both names.

_adb_m_target=()          # transport selector, filled by _adb_m_scan_target
_adb_m_devcmd_cache=""    # device executables, queried at most once per shell

# Run the binary against the selected transport. Read-only device queries go
# through here, so they are time-limited: completing must not hang the prompt
# when nothing is attached.
_adb_m_adb() {
    local bin="${COMP_WORDS[0]}"
    if command -v timeout >/dev/null 2>&1; then
        timeout 3 "$bin" ${_adb_m_target[@]+"${_adb_m_target[@]}"} "$@" 2>/dev/null
    else
        "$bin" ${_adb_m_target[@]+"${_adb_m_target[@]}"} "$@" 2>/dev/null
    fi
}

# Find `-s SERIAL` / `-t ID` / `--serial=` anywhere before the cursor so device
# queries hit the same transport the user asked for.
_adb_m_scan_target() {
    _adb_m_target=()
    local i
    for ((i = 1; i < COMP_CWORD; i++)); do
        case "${COMP_WORDS[i]}" in
            -s|-t)
                [[ -n "${COMP_WORDS[i+1]}" ]] && _adb_m_target=("${COMP_WORDS[i]}" "${COMP_WORDS[i+1]}")
                ;;
            --serial=*) _adb_m_target=(-s "${COMP_WORDS[i]#--serial=}") ;;
        esac
    done
    [[ ${#_adb_m_target[@]} -eq 0 && -n "${ANDROID_SERIAL:-}" ]] && _adb_m_target=(-s "${ANDROID_SERIAL:-}")
}

# Serials of attached devices (for -s and `disconnect`).
_adb_m_serials() {
    local out
    out=$(_adb_m_adb devices | sed -e '1d' -e 's/[[:space:]].*$//' | grep -v '^$')
    [[ -n "$out" ]] && printf '%s\n' "$out"
}

# Remote paths: `ls -dp` marks directories with a trailing slash and does not
# recurse, which is exactly the shape a completer wants.
_adb_m_remote() {
    local cur="$1" out
    [[ -z "$cur" ]] && cur=/
    out=$(_adb_m_adb shell ls -dp -- "${cur}"'*' | tr -d '\r')
    [[ -z "$out" ]] && return 0
    if [[ $(type -t compopt) == builtin ]]; then
        compopt -o nospace 2>/dev/null
    fi
    local IFS=$'\n'
    COMPREPLY+=( $(compgen -W "$out" -- "$cur") )
}

# Executables on the device, from its $PATH. Cached: this lists a few thousand
# entries and nobody wants that latency on every TAB.
_adb_m_devcmds() {
    local cur="$1"
    if [[ -z "$_adb_m_devcmd_cache" ]]; then
        local paths
        paths=$(_adb_m_adb shell 'echo $PATH' | tr -d '\r' | tr : ' ')
        [[ -z "$paths" ]] && return 0
        # ls of several directories prints a "dir:" header per directory;
        # those are not executables, so drop them (and blank lines).
        _adb_m_devcmd_cache=$(_adb_m_adb shell ls $paths | tr -d '\r' | tr ' ' '\n' |
                              grep -v '^$' | grep -v ':$' | sort -u | tr '\n' ' ')
    fi
    [[ -z "$_adb_m_devcmd_cache" ]] && return 0
    COMPREPLY+=( $(compgen -W "$_adb_m_devcmd_cache" -- "$cur") )
}

# Installed packages, for `uninstall` and `shell pm ...`.
_adb_m_packages() {
    local cur="$1" out
    out=$(_adb_m_adb shell pm list packages | tr -d '\r' | sed 's/^package://')
    [[ -z "$out" ]] && return 0
    COMPREPLY+=( $(compgen -W "$out" -- "$cur") )
}

_adb_m_local() {
    # local files, with the caller's filter (e.g. '*.apk'); directories always
    # allowed so a path can be walked into
    local cur="$1" filt="$2"
    if [[ $(type -t compopt) == builtin ]]; then
        compopt -o plusdirs 2>/dev/null
        if [[ -z "$filt" ]]; then
            COMPREPLY+=( $(compgen -f -- "$cur") )
        else
            COMPREPLY+=( $(compgen -f -X "!$filt" -- "$cur") )
        fi
    else
        local IFS=$'\n'
        COMPREPLY+=( $(compgen -d -- "$cur") )
        if [[ -z "$filt" ]]; then
            COMPREPLY+=( $(compgen -f -- "$cur") )
        else
            COMPREPLY+=( $(compgen -f -X "!$filt" -- "$cur") )
        fi
    fi
}

_adb_m() {
    local cur prev i cmd cmd_i nargs
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    COMPREPLY=()
    _adb_m_scan_target

    local cmds=')B";
    o << Join(CommandList());
    o << R"B('
    local opts=')B";
    o << OptionList();
    o << R"B('
    local langs=')B";
    o << LangList();
    o << R"B('

    # ---- option values -------------------------------------------------
    case "$prev" in
        -s) COMPREPLY=( $(_adb_m_serials) ); return 0 ;;
        -t) COMPREPLY=( $(compgen -W "$(_adb_m_adb devices -l | sed -e '1d' -e 's/.*transport_id://' -e 's/[^0-9].*$//')" -- "$cur") ); return 0 ;;
        -z) COMPREPLY=( $(compgen -W ")B";
    o << kCompression;
    o << R"B(" -- "$cur") ); return 0 ;;
        -e) return 0 ;;
        -H|-P|-L) return 0 ;;
        --lang) COMPREPLY=( $(compgen -W "$langs" -- "$cur") ); return 0 ;;
    esac
    case "$cur" in
        --lang=*) COMPREPLY=( $(compgen -W "$langs" -- "${cur#--lang=}") ); return 0 ;;
    esac

    # ---- options -------------------------------------------------------
    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "$opts" -- "$cur") )
        return 0
    fi

    # ---- locate the command, skipping options and their values ----------
    cmd=""
    cmd_i=0
    for ((i = 1; i <= COMP_CWORD; i++)); do
        case "${COMP_WORDS[i]}" in
)B";
    for (const char* v = kValueOpts; *v;) {
        // emit one case arm per value option
        const char* sp = strchr(v, ' ');
        std::string tok(v, sp ? (size_t)(sp - v) : strlen(v));
        o << "            " << tok << ") ((i++)); continue ;;\n";
        if (!sp) break;
        v = sp + 1;
    }
    o << R"B(        esac
        [[ "${COMP_WORDS[i]}" == -* ]] && continue
        cmd="${COMP_WORDS[i]}"; cmd_i=$i
        break
    done

    if [[ -z "$cmd" ]]; then
        COMPREPLY=( $(compgen -W "$cmds $opts" -- "$cur") )
        return 0
    fi

    # positional argument count after the command, options excluded
    nargs=0
    for ((i = cmd_i + 1; i < COMP_CWORD; i++)); do
        [[ "${COMP_WORDS[i]}" == -* ]] && continue
        ((nargs++))
    done

    case "$cmd" in
        push)
            # push LOCAL... REMOTE — locals first, then one remote path
            if ((nargs == 0)); then _adb_m_local "$cur" ""
            else _adb_m_remote "$cur"; fi
            ;;
        pull)
            # pull REMOTE... LOCAL — remotes first, then locals
            if ((nargs == 0)); then _adb_m_remote "$cur"
            else _adb_m_local "$cur" ""; fi
            ;;
        sync)
            ((nargs == 0)) && COMPREPLY=( $(compgen -W ")B";
    o << kSyncTargets;
    o << R"B(" -- "$cur") )
            ;;
        shell)
            # `adb shell <TAB>` -> the device's executables; `adb shell ls /sy<TAB>`
            # -> remote paths. Anything past the first token that looks like a
            # path gets remote completion.
            if [[ "$cur" == /* || "$cur" == ./* || "$cur" == ../* || "$cur" == ~* ]]; then
                _adb_m_remote "$cur"
            elif ((nargs == 0)); then
                _adb_m_devcmds "$cur"
            else
                case "${COMP_WORDS[cmd_i+1]}" in
                    ls|cat) _adb_m_remote "$cur" ;;
                    dumpsys)
                        ((nargs == 1)) && COMPREPLY=( $(compgen -W "-l $(_adb_m_adb shell dumpsys -l | tr -d '\r' | sed -e '1d' -e 's/^[[:space:]]*//')" -- "$cur") )
                        ;;
                    pm)
                        if ((nargs == 1)); then
                            COMPREPLY=( $(compgen -W "-l -lf -p clear dump enable disable grant hide install list path revoke set-install-location trim-caches uninstall" -- "$cur") )
                        elif ((nargs == 2)) && [[ "${COMP_WORDS[cmd_i+2]}" == "list" ]]; then
                            COMPREPLY=( $(compgen -W "packages permission-groups permissions instrumentation features libraries users" -- "$cur") )
                        else
                            _adb_m_packages "$cur"
                        fi
                        ;;
                    am)
                        ((nargs == 1)) && COMPREPLY=( $(compgen -W "broadcast force-stop instrument kill start start-service stop-service to-uri" -- "$cur") )
                        ;;
                    settings)
                        ((nargs == 1)) && COMPREPLY=( $(compgen -W "get put delete list global system secure" -- "$cur") )
                        ;;
                esac
            fi
            ;;
        install|install-multiple|install-multi-package)
            _adb_m_local "$cur" "*.apk"
            ;;
        uninstall)
            _adb_m_packages "$cur"
            ;;
        sideload)
            _adb_m_local "$cur" "*.zip"
            ;;
        keygen|bugreport)
            _adb_m_local "$cur" ""
            ;;
        reboot)
            ((nargs == 0)) && COMPREPLY=( $(compgen -W ")B";
    o << kRebootTargets;
    o << R"B(" -- "$cur") )
            ;;
        disconnect)
            COMPREPLY=( $(compgen -W "$(_adb_m_serials)" -- "$cur") )
            ;;
        forward|reverse)
            ((nargs == 0)) && COMPREPLY=( $(compgen -W "--no-rebind )B";
    o << kForwardSubs;
    o << R"B(" -- "$cur") )
            ;;
        mdns)
            ((nargs == 0)) && COMPREPLY=( $(compgen -W ")B";
    o << kMdnsSubs;
    o << R"B(" -- "$cur") )
            ;;
        help)
            ((nargs == 0)) && COMPREPLY=( $(compgen -W "--list-sections )B";
    o << Join(adbhelp::SectionKeywords());
    o << R"B(" -- "$cur") )
            ;;
        wait-for-*)
            COMPREPLY=( $(compgen -W "$cmds" -- "$cur") )
            ;;
    esac
    return 0
}

if [[ $(type -t compopt) == builtin ]]; then
    complete -F _adb_m adb-m adb-meowarch
else
    complete -o nospace -F _adb_m adb-m adb-meowarch
fi
)B";
    return o.str();
}

