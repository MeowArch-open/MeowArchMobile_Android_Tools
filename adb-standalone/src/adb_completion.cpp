std::string ZshScript() {
    std::ostringstream o;
    o << R"Z(#compdef adb-m adb-meowarch
# zsh completion for adb-m / adb-meowarch.
# GENERATED by `adb-m --shell-completion=zsh` — do not edit by hand.
# Install as /usr/share/zsh/site-functions/_adb-m and _adb-meowarch (same
# content; the #compdef line above registers both names).

_adb_m_target=()
_adb_m_devcmd_cache=""

_adb_m_adb() {
  local bin=${words[1]}
  if (( $+commands[timeout] )); then
    timeout 3 "$bin" ${_adb_m_target[@]} "$@" 2>/dev/null
  else
    "$bin" ${_adb_m_target[@]} "$@" 2>/dev/null
  fi
}

_adb_m_scan_target() {
  _adb_m_target=()
  local i
  for ((i = 2; i < CURRENT; i++)); do
    case ${words[i]} in
      (-s|-t) [[ -n ${words[i+1]} ]] && _adb_m_target=(${words[i]} ${words[i+1]}) ;;
      (--serial=*) _adb_m_target=(-s ${words[i]#--serial=}) ;;
    esac
  done
  (( ${#_adb_m_target} == 0 && -n ${ANDROID_SERIAL:-} )) && _adb_m_target=(-s ${ANDROID_SERIAL:-})
}

_adb_m_serials() {
  local -a out
  out=(${(f)"$(_adb_m_adb devices | sed -e '1d' -e 's/[[:space:]].*$//' | grep -v '^$')"})
  (( ${#out} )) && compadd -a out
}

_adb_m_remote() {
  # `ls -dp`: directories come back with a trailing slash, no recursion.
  local -a out
  out=(${(f)"$(_adb_m_adb shell ls -dp -- "${1:-/}"'*' | tr -d '\r' | grep -v '^$')"})
  (( ${#out} )) || return 1
  compadd -Q -S '' -f -- $out
}

_adb_m_devcmds() {
  if [[ -z $_adb_m_devcmd_cache ]]; then
    local paths
    paths=$(_adb_m_adb shell 'echo $PATH' | tr -d '\r' | tr : ' ')
    [[ -z $paths ]] && return 1
    # ls of several directories prints a "dir:" header per directory; drop those.
    _adb_m_devcmd_cache=$(_adb_m_adb shell ls $paths | tr -d '\r' | tr ' ' '\n' | grep -v '^$' | grep -v ':$' | sort -u | tr '\n' ' ')
  fi
  [[ -z $_adb_m_devcmd_cache ]] && return 1
  compadd -Q -- ${(s: :)_adb_m_devcmd_cache}
}

_adb_m_packages() {
  local -a out
  out=(${(f)"$(_adb_m_adb shell pm list packages | tr -d '\r' | sed 's/^package://')"})
  (( ${#out} )) && compadd -a out
}

_adb_m() {
  local -a cmds opts langs
  cmds=()Z";
    for (const auto& c : CommandList()) o << c << " ";
    o << ")\n  opts=(";
    for (const auto& op : adbhelp::Options()) o << op << " ";
    o << ")\n  langs=(" << LangList() << ")\n"
      << R"Z(  local cur=${words[CURRENT]} prev=${words[CURRENT-1]}
  local i cmd='' cmd_i=0 nargs=0
  _adb_m_scan_target

  # option values
  case $prev in
    (-s) _adb_m_serials; return ;;
    (-t)
      local -a tids
      tids=(${(f)"$(_adb_m_adb devices -l | sed -e '1d' -e 's/.*transport_id://' -e 's/[^0-9].*$//')"})
      (( ${#tids} )) && compadd -a tids
      return ;;
    (-z) compadd -- )Z"
      << kCompression << R"Z(; return ;;
    (--lang) compadd -- $langs; return ;;
    (-e|-H|-P|-L) return ;;
  esac
  case $cur in
    (--lang=*) compadd -Q -P '--lang=' -- $langs; return ;;
  esac

  if [[ $cur == -* ]]; then
    compadd -a opts
    return
  fi

  # locate the command, skipping options and their values
  for ((i = 2; i < CURRENT; i++)); do
    case ${words[i]} in
)Z";
    for (const char* v = kValueOpts; *v;) {
        const char* sp = strchr(v, ' ');
        std::string tok(v, sp ? (size_t)(sp - v) : strlen(v));
        o << "      (" << tok << ") ((i++)); continue ;;\n";
        if (!sp) break;
        v = sp + 1;
    }
    o << R"Z(    esac
    [[ ${words[i]} == -* ]] && continue
    cmd=${words[i]}; cmd_i=$i; break
  done

  if [[ -z $cmd ]]; then
    compadd -a cmds opts
    return
  fi

  for ((i = cmd_i + 1; i < CURRENT; i++)); do
    [[ ${words[i]} == -* ]] && continue
    ((nargs++))
  done

  case $cmd in
    (push)
      if ((nargs == 0)); then _files
      else _adb_m_remote "$cur"; fi ;;
    (pull)
      if ((nargs == 0)); then _adb_m_remote "$cur"
      else _files; fi ;;
    (sync)
      ((nargs == 0)) && compadd -- )Z"
      << kSyncTargets << R"Z( ;;
    (shell)
      if [[ $cur == /* || $cur == ./* || $cur == ../* || $cur == ~* ]]; then
        _adb_m_remote "$cur"
      elif ((nargs == 0)); then
        _adb_m_devcmds
      else
        case ${words[cmd_i+1]} in
          (ls|cat) _adb_m_remote "$cur" ;;
          (dumpsys)
            ((nargs == 1)) && { local -a svcs; svcs=(-l ${(f)"$(_adb_m_adb shell dumpsys -l | tr -d '\r' | sed -e '1d' -e 's/^[[:space:]]*//')"}); compadd -a svcs; } ;;
          (pm)
            if ((nargs == 1)); then
              compadd -- -l -lf -p clear dump enable disable grant hide install list path revoke set-install-location trim-caches uninstall
            elif ((nargs == 2)) && [[ ${words[cmd_i+2]} == list ]]; then
              compadd -- packages permission-groups permissions instrumentation features libraries users
            else
              _adb_m_packages
            fi ;;
          (am)
            ((nargs == 1)) && compadd -- broadcast force-stop instrument kill start start-service stop-service to-uri ;;
          (settings)
            ((nargs == 1)) && compadd -- get put delete list global system secure ;;
        esac
      fi ;;
    (install|install-multiple|install-multi-package)
      _files -g '*.apk' ;;
    (uninstall) _adb_m_packages ;;
    (sideload) _files -g '*.zip' ;;
    (keygen|bugreport) _files ;;
    (reboot) ((nargs == 0)) && compadd -- )Z"
      << kRebootTargets << R"Z( ;;
    (disconnect) _adb_m_serials ;;
    (forward|reverse) ((nargs == 0)) && compadd -- --no-rebind )Z"
      << kForwardSubs << R"Z( ;;
    (mdns) ((nargs == 0)) && compadd -- )Z"
      << kMdnsSubs << R"Z( ;;
    (help) ((nargs == 0)) && compadd -- --list-sections )Z"
      << Join(adbhelp::SectionKeywords()) << R"Z( ;;
    (wait-for-*) compadd -a cmds ;;
  esac
}

_adb_m "$@"
)Z";
    return o.str();
}

