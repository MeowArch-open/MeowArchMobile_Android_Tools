/*
 * adb_completion.cpp — see adb_completion.h.
 *
 * Vocabulary comes from the help table (adb_help::Commands / Options) and the
 * i18n registry, so `adb help` and what the shells complete cannot drift apart.
 * The argument rules below mirror what commandline.cpp actually accepts.
 *
 * Device-side completion (remote paths, device executables, package names) is a
 * read-only `adb shell` query. Two rules keep it from being a liability:
 *   * it is time-limited (timeout 3), because completing must not hang the
 *     prompt when nothing is attached or the device is asleep;
 *   * results are cached per shell session, so repeated TAB does not re-query.
 * When the query comes back empty the shell falls back to its own file
 * completion, which is what you want when pushing a local file.
 */
#include "adb_completion.h"

#include <ctype.h>
#include <string.h>

#include <algorithm>
#include <sstream>
#include <string>
#include <vector>

#include "adb_help.h"
#include "adb_i18n.h"

