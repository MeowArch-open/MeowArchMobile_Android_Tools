#!/usr/bin/env python3
"""make_payload.py — build a real Android payload.bin for the flash-x tests.

Usage:
    make_payload.py OUT_PATH [--size BYTES] [--codec raw|xz|bz2]
                           [--parts NAME[,NAME...]] [--ops N] [--block-size N]
                           [--no-hash] [--no-op-hash] [--no-dst-length]
                           [--short-data BYTES] [--xz-check crc64|crc32|sha256|none]
                           [--delta] [--corrupt]

Writes a major-version-2 payload exactly as update_engine does:

    "CrAU" | u64 major=2 | u64 manifest_len | u32 manifest_sig_len
    manifest (protobuf DeltaArchiveManifest)
    manifest signature (zeroed here; a real one is RSA over the manifest)
    data section (concatenated op blobs; op.data_offset is relative to here)

The protobuf is emitted by hand with the same varint/length-delimited encoding
the parser under test reads, so the test exercises real field numbers rather
than a shortcut. Partition content is pseudo-random but reproducible, so the
expected image can be regenerated byte for byte and compared after extraction.

--codec picks how each op blob is stored: raw (REPLACE), xz (REPLACE_XZ) or
bz2 (REPLACE_BZ). --ops splits a partition across several operations with
disjoint destination extents, which is what real payloads do for big partitions.
--delta emits a SOURCE_COPY operation, which flash-x must refuse.
--corrupt flips a byte in the middle of the data section, which must trip the
SHA-256 check.
--no-dst-length omits InstallOperation.dst_length (delta_generator omits it for
REPLACE*; the proto documents it for BSDIFF), so the extractor has to derive
the expected size from dst_extents.
--short-data N declares data_length N bytes smaller than the stored blob while
leaving the file intact — the case only the extent-size comparison catches.
"""
import argparse
import hashlib
import lzma
import os
import struct
import sys

try:
    import bz2 as bz2mod
except ImportError:  # pragma: no cover
    bz2mod = None

MAJOR = 2
DEFAULT_BLOCK = 4096


def varint(n: int) -> bytes:
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def tag(field: int, wire: int) -> bytes:
    return varint((field << 3) | wire)


def vfield(field: int, value: int) -> bytes:
    """varint field; omitted when the value is 0, as protobuf does."""
    return b"" if value == 0 else tag(field, 0) + varint(value)


def lfield(field: int, blob: bytes) -> bytes:
    return tag(field, 2) + varint(len(blob)) + blob


def sfield(field: int, text: str) -> bytes:
    return lfield(field, text.encode())


def extent(start_block: int, num_blocks: int) -> bytes:
    return vfield(1, start_block) + vfield(2, num_blocks)


def partition_content(name: str, size: int) -> bytes:
    """Reproducible, incompressible content for a partition image.

    Derived from the name alone, so tests can regenerate the expected bytes
    without reading the payload back. tests/test_flash_x.py imports this
    function rather than duplicating it, so the two can never drift.
    """
    out = bytearray()
    i = 0
    while len(out) < size:
        out += hashlib.sha256(f"{name}:{i}".encode()).digest()
        i += 1
    return bytes(out[:size])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--size", type=int, default=1 << 20)
    ap.add_argument("--codec", choices=("raw", "xz", "bz2"), default="xz")
    ap.add_argument("--parts", default="boot,system,vbmeta")
    ap.add_argument("--no-hash", action="store_true",
                    help="omit both per-op and per-partition SHA-256")
    ap.add_argument("--no-op-hash", action="store_true",
                    help="omit per-op SHA-256 only, so the whole-image check is "
                         "what catches corruption")
    ap.add_argument("--delta", action="store_true")
    ap.add_argument("--corrupt", action="store_true")
    ap.add_argument("--block-size", type=int, default=DEFAULT_BLOCK)
    ap.add_argument("--short-data", type=int, default=0, metavar="BYTES",
                    help="declare each op's data_length BYTES shorter than the "
                         "blob actually stored, so the file reads fine but the op "
                         "cannot fill its destination extents. With --no-hash and "
                         "--no-dst-length this is only detectable by deriving the "
                         "expected size from dst_extents.")
    ap.add_argument("--no-dst-length", action="store_true",
                    help="omit InstallOperation.dst_length, as delta_generator "
                         "does for REPLACE/REPLACE_BZ/REPLACE_XZ (the proto "
                         "documents it as BSDIFF-only); the extractor must then "
                         "rely on dst_extents alone")
    ap.add_argument("--xz-check", choices=("crc64", "crc32", "sha256", "none"),
                    default="crc64",
                    help="xz integrity check in the stream. crc64 is what "
                         "delta_generator emits; sha256 exercises xz-embedded's "
                         "XZ_UNSUPPORTED_CHECK path, which must decode and skip "
                         "the check rather than reject the stream")
    ap.add_argument("--ops", type=int, default=1)
    args = ap.parse_args()

    block = args.block_size
    size = (args.size + block - 1) // block * block
    names = [n for n in args.parts.split(",") if n]

    data = bytearray()       # data section
    partitions = bytearray()  # manifest.partitions (field 13)

    for name in names:
        content = partition_content(name, size)
        ops = bytearray()
        per_op = (size + args.ops - 1) // args.ops
        per_op = (per_op + block - 1) // block * block
        start = 0
        while start < size:
            span = min(per_op, size - start)
            piece = content[start:start + span]
            dst_off = start // block
            dst_blocks = span // block

            if args.delta:
                # SOURCE_COPY(4): needs the on-device partition; must be refused.
                op = (vfield(1, 4)
                      + lfield(4, extent(dst_off, dst_blocks))   # src_extents
                      + vfield(5, span)                          # src_length
                      + lfield(6, extent(dst_off, dst_blocks))   # dst_extents
                      + (b"" if args.no_dst_length else vfield(7, span)))
            else:
                if args.codec == "raw":
                    blob, optype = piece, 0
                elif args.codec == "xz":
                    check = {"crc64": lzma.CHECK_CRC64, "crc32": lzma.CHECK_CRC32,
                             "sha256": lzma.CHECK_SHA256, "none": lzma.CHECK_NONE}[
                        args.xz_check]
                    blob, optype = lzma.compress(
                        piece, format=lzma.FORMAT_XZ, check=check,
                        filters=[{"id": lzma.FILTER_LZMA2, "preset": 6}]), 8
                else:
                    if bz2mod is None:
                        print("python bz2 unavailable", file=sys.stderr)
                        return 2
                    blob, optype = bz2mod.compress(piece, 9), 1

                data_off = len(data)
                data.extend(blob)
                declared = max(0, len(blob) - args.short_data)
                op = (vfield(1, optype)
                      + vfield(2, data_off)          # data_offset
                      + vfield(3, declared)          # data_length
                      + lfield(6, extent(dst_off, dst_blocks))
                      + (b"" if args.no_dst_length else vfield(7, span)))
                if not (args.no_hash or args.no_op_hash):
                    op += lfield(8, hashlib.sha256(blob[:declared]).digest())

            ops += lfield(8, op)  # PartitionUpdate.operations = 8
            start += span

        part = sfield(1, name)    # partition_name
        if not args.no_hash:
            info = vfield(1, size) + lfield(2, hashlib.sha256(content).digest())
            part += lfield(7, info)   # new_partition_info
        part += ops
        partitions += lfield(13, part)

    manifest = (vfield(3, block)            # block_size
                + vfield(12, 0)             # minor_version: full payload
                + bytes(partitions))
    sig_len = 256

    with open(args.out, "wb") as f:
        f.write(b"CrAU")
        f.write(struct.pack(">QQI", MAJOR, len(manifest), sig_len))
        f.write(manifest)
        f.write(b"\0" * sig_len)
        f.write(data)

    if args.corrupt and len(data) > 64:
        # Flip bytes past the data base so the stored blob no longer matches
        # its recorded SHA-256.
        with open(args.out, "r+b") as f:
            base = 24 + len(manifest) + sig_len
            f.seek(base + 32)
            f.write(bytes([f.read(1)[0] ^ 0xFF]))

    print(f"{args.out}: {len(names)} partition(s), codec={args.codec}, "
          f"size={size}, ops/partition={args.ops}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

# The protobuf field builders are imported by tests/test_flash_x.py to
# hand-write hostile manifests (absurd extents, wrong major version, garbage
# bodies), so they are part of this module's contract, not an implementation
# detail.
__all__ = ["partition_content", "varint", "tag", "vfield", "lfield", "sfield",
           "extent"]
